def set_seed(seed: int = 42) -> None:
    """Seed Python and NumPy. The game engine seeds itself from hardware
    entropy (std::random_device), so simulated games are never exactly
    reproducible - we report confidence intervals instead."""
    random.seed(seed)
    np.random.seed(seed)


def wilson_ci(wins: float, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score interval for a win rate (better than +-1.96*SE near 0/1)."""
    if n == 0:
        return (float("nan"), float("nan"))
    p = wins / n
    denom = 1 + z**2 / n
    centre = (p + z**2 / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / denom
    return (centre - half, centre + half)


