def bar_with_labels(ax, series, fmt="{:.0f}", horizontal=True, color=PALETTE[0]):
    """Bar chart of a pandas Series with value labels."""
    if horizontal:
        ax.barh(series.index.astype(str), series.values, color=color)
        ax.invert_yaxis()
        for i, v in enumerate(series.values):
            ax.text(v, i, " " + fmt.format(v), va="center", fontsize=9)
    else:
        ax.bar(series.index.astype(str), series.values, color=color)
        for i, v in enumerate(series.values):
            ax.text(i, v, fmt.format(v), ha="center", va="bottom", fontsize=9)
    return ax


