MAIN_PY = '''"""Kaggle entry point - generated by src/utils.py:build_submission.

Kaggle exec()s this file without __file__ and uses the LAST callable defined,
so `agent` must stay the final definition in this file.
"""
import os
import sys


def _agent_dir():
    for d in ["/kaggle_simulations/agent", *sys.path, os.getcwd()]:
        if d and os.path.exists(os.path.join(d, "card_db.json")):
            return d
    raise FileNotFoundError("card_db.json not found")


_DIR = _agent_dir()
if _DIR not in sys.path:
    sys.path.insert(0, _DIR)

from ptcg_policy import HeuristicPolicy as _HeuristicPolicy, load_card_db_json as _load  # noqa: E402

with open(os.path.join(_DIR, "deck.csv")) as _f:
    _DECK = [int(x) for x in _f.read().split() if x.strip()][:60]
_POLICY = _HeuristicPolicy(_load(os.path.join(_DIR, "card_db.json")), _DECK, seed=0)


def agent(obs):
    return _POLICY(obs)
'''


def build_submission(card_db: dict, deck: list[int], out_dir: Path | str = BUILD_DIR,
                     policy_source: Path | str = "src/models.py") -> Path:
    """Write main.py + ptcg_policy.py + card_db.json + deck.csv and pack them.

    Only the cards in our deck are written to card_db.json (smaller bundle).
    Returns the path of ``submission.tar.gz`` (main.py at the top level, as
    Kaggle requires).
    """
    out_dir = Path(out_dir)
    bundle = out_dir / "agent"
    if bundle.exists():
        shutil.rmtree(bundle)
    bundle.mkdir(parents=True)
    keep = {str(c) for c in deck}
    attack_ids = {str(a) for c in keep for a in card_db["cards"][c]["attacks"]}
    small_db = {"cards": {c: card_db["cards"][c] for c in keep},
                "attacks": {a: card_db["attacks"][a] for a in attack_ids}}
    (bundle / "main.py").write_text(MAIN_PY)
    shutil.copy(policy_source, bundle / "ptcg_policy.py")
    (bundle / "card_db.json").write_text(json.dumps(small_db))
    (bundle / "deck.csv").write_text("\n".join(str(c) for c in deck) + "\n")
    tar_path = out_dir / "submission.tar.gz"
    with tarfile.open(tar_path, "w:gz") as tar:
        for f in sorted(os.listdir(bundle)):
            tar.add(bundle / f, arcname=f)
    return tar_path
